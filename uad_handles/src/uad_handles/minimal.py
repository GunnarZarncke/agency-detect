def main() -> None:
    parser = argparse.ArgumentParser()
    from uad_handles import default_outdir

    parser.add_argument("--outdir", type=Path, default=default_outdir("minimal"))
    parser.add_argument("--seeds", type=int, default=1)
    parser.add_argument("--passive-n", type=int, default=800)
    parser.add_argument("--intervention-batch", type=int, default=100)
    parser.add_argument("--rounds", type=int, default=3)
    args = parser.parse_args()

    seeds = list(range(args.seeds))
    summary, history = run_benchmark(seeds, args.passive_n, args.intervention_batch, args.rounds, args.outdir)
    # Plotting is optional and can be slow on fresh containers due to font cache setup.
    if plt is not None and False:
        maybe_plot(summary, history, args.outdir)

    print("Variables:", ", ".join(f"{i}:{name}" for i, name in enumerate(VAR_NAMES)))
    print("True loop:", Candidate(*TRUE_LOOP).pretty())
    print("\nBenchmark summary:")
    print(summary.describe(include="all").to_string())
    print("\nSuccess rates:")
    print(f"  plain passive UAD:      {summary['plain_top_true'].mean():.3f}")
    print(f"  active handle-UAD:      {summary['active_top_true'].mean():.3f}")
    print("\nMedian true ranks:")
    print(f"  plain passive UAD:      {summary['plain_true_rank'].median():.1f}")
    print(f"  active handle-UAD:      {summary['active_true_rank'].median():.1f}")
    print(f"\nWrote outputs to {args.outdir}")


if __name__ == "__main__":
    main()
